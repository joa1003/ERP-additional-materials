from __future__ import annotations

"""Build the household-level analytical dataset used by reported post-hoc analyses.

The input tables are generated by the metric-generation stages after forecasting.
Native-support metrics are used for same-lead strategy comparisons. Strict common
support is used for cross-lead comparisons. The script averages the four formal
seeds at household level, computes the four locked strategy gains, and creates the
wide analytical bridge consumed by profile-group and later post-hoc analyses.

Positive gain means lower error for the first named strategy:
- source_transfer_gain: Scratch Limited - Direct Transfer
- fine_tuning_gain: Direct Transfer - Fine Tuning
- full_data_gain: Scratch Limited - Scratch Full
- direct_vs_full_gain: Scratch Full - Direct Transfer
"""

import argparse
import json
import os
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

LEADS = (1, 12, 48)
SEEDS = (42, 123, 2026, 31415)
STRATEGIES = (
    "direct_transfer",
    "fine_tuning",
    "cer_scratch_limited",
    "cer_scratch_full",
)
ERROR_CRITERIA = {
    "mae": "mae_kwh",
    "rmse": "rmse_kwh",
    "smape": "smape_percent",
}
EXPECTED_HOUSEHOLDS = 929
EXPECTED_ROWS_PER_LEAD = EXPECTED_HOUSEHOLDS * len(STRATEGIES) * len(SEEDS)
EXPECTED_ALL_ROWS = EXPECTED_ROWS_PER_LEAD * len(LEADS)
TIE_TOLERANCE = 1e-12

NATIVE_REQUIRED = (
    "strategy", "seed", "entity_id", "observations",
    "actual_mean_kwh", "actual_std_kwh", "actual_zero_rate",
    "mae_kwh", "rmse_kwh", "smape_percent", "bias_kwh",
)
NATIVE_OPTIONAL = (
    "overprediction_rate", "underprediction_rate", "exact_prediction_rate",
    "negative_prediction_rate", "daily_seasonal_naive_mae_kwh",
    "daily_seasonal_naive_rmse_kwh", "daily_seasonal_naive_smape_percent",
    "persistence_mae_kwh", "persistence_rmse_kwh", "persistence_smape_percent",
    "nmae_by_actual_mean", "nrmse_by_actual_mean", "nrmse_by_actual_std",
    "relative_mae_vs_daily_naive", "relative_rmse_vs_daily_naive",
    "relative_smape_vs_daily_naive", "mae_skill_vs_daily_naive",
    "rmse_skill_vs_daily_naive", "smape_skill_vs_daily_naive",
)


