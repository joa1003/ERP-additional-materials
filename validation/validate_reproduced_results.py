#!/usr/bin/env python3
"""Verify a completed reproduction against a compact set of reported anchors.

This script reads only outputs generated by the public workflow. It never reads the
bundled reference-output directory and is not a prerequisite for computation.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
EXPECTATIONS = json.loads((ROOT / "validation/reference_expectations.json").read_text(encoding="utf-8"))


def fail(message: str) -> None:
    raise RuntimeError(message)


def require(path: Path) -> Path:
    if not path.is_file():
        fail(f"Required generated output is missing: {path.relative_to(ROOT)}")
    return path


def check_close(name: str, actual: float, expected: float, tolerance: float, rows: list[dict]) -> None:
    difference = abs(float(actual) - float(expected))
    passed = math.isfinite(float(actual)) and difference <= tolerance
    rows.append(
        {
            "check": name,
            "expected": float(expected),
            "actual": float(actual),
            "absolute_difference": difference,
            "tolerance": float(tolerance),
            "pass": passed,
        }
    )


def check_equal(name: str, actual: int, expected: int, rows: list[dict]) -> None:
    rows.append(
        {
            "check": name,
            "expected": int(expected),
            "actual": int(actual),
            "absolute_difference": abs(int(actual) - int(expected)),
            "tolerance": 0,
            "pass": int(actual) == int(expected),
        }
    )


def verify_native_h12(rows: list[dict]) -> None:
    spec = EXPECTATIONS["h12_native_pooled_mae_mean"]
    tolerance = float(spec["tolerance"])
    seeds = [int(value) for value in EXPECTATIONS["formal_counts"]["seeds"]]
    for strategy in (
        "direct_transfer",
        "fine_tuning",
        "cer_scratch_limited",
        "cer_scratch_full",
    ):
        values: list[float] = []
        for seed in seeds:
            path = require(
                ROOT
                / "outputs/tables/pooled_strategy_evaluation_formal"
                / "h12"
                / strategy
                / f"seed_{seed}"
                / "test_pooled_metrics.csv"
            )
            frame = pd.read_csv(path)
            if len(frame) != 1 or "mae_kwh" not in frame.columns:
                fail(f"Unexpected pooled metric schema: {path.relative_to(ROOT)}")
            if "strategy" in frame.columns and str(frame.iloc[0]["strategy"]) != strategy:
                fail(f"Strategy label mismatch in {path.relative_to(ROOT)}")
            values.append(float(frame.iloc[0]["mae_kwh"]))
        actual = sum(values) / len(values)
        check_close(
            f"h12 native pooled MAE four-seed mean: {strategy}",
            actual,
            float(spec[strategy]),
            tolerance,
            rows,
        )


def verify_group_gain(rows: list[dict]) -> None:
    path = require(
        ROOT
        / "outputs/tables/cross_strategy_profile_group_cross_strategy_profile_group_appendix_closure"
        / "cross_strategy_profile_group_table_k1a_profile_group_gains.csv"
    )
    frame = pd.read_csv(path)
    required = {"comparison_code", "outcome", "G1", "G2", "G3", "G4"}
    missing = sorted(required - set(frame.columns))
    if missing:
        fail(f"Profile-group table lacks columns {missing}: {path.relative_to(ROOT)}")
    hit = frame.loc[
        frame["comparison_code"].astype(str).eq("direct_over_limited")
        & frame["outcome"].astype(str).eq("MAE Gain (kWh)")
    ]
    if len(hit) != 1:
        fail("Expected exactly one Direct-over-Limited MAE Gain row in generated profile-group table")
    row = hit.iloc[0]
    spec = EXPECTATIONS["h12_group_source_transfer_mae_gain"]
    tolerance = float(spec["tolerance"])
    for group in ("G1", "G2", "G3", "G4"):
        check_close(
            f"h12 L-D household MAE gain: {group}",
            float(row[group]),
            float(spec[group]),
            tolerance,
            rows,
        )


def verify_cohort_counts(rows: list[dict]) -> None:
    counts = EXPECTATIONS["formal_counts"]
    source_path = require(
        ROOT
        / "outputs/tables/profile_clustering_clustering_final_decision_dissertation"
        / "profile_clustering_final_selected_source_assignments.parquet"
    )
    source = pd.read_parquet(source_path)
    source_id = "household_id" if "household_id" in source.columns else "entity_id"
    if source_id not in source.columns:
        fail(f"No source household identifier in {source_path.relative_to(ROOT)}")
    check_equal(
        "formal source households",
        source[source_id].astype(str).nunique(),
        int(counts["lcl_households"]),
        rows,
    )

    target_path = require(
        ROOT
        / "outputs/tables/target_profile_assignment_cer_assignment"
        / "target_profile_assignment_cer_source_defined_assignments.csv"
    )
    target = pd.read_csv(target_path)
    target_id = "meter_id" if "meter_id" in target.columns else "entity_id"
    if target_id not in target.columns:
        fail(f"No target household identifier in {target_path.relative_to(ROOT)}")
    check_equal(
        "formal target households",
        target[target_id].astype(str).nunique(),
        int(counts["cer_households"]),
        rows,
    )


def main() -> int:
    rows: list[dict] = []
    try:
        verify_native_h12(rows)
        verify_group_gain(rows)
        verify_cohort_counts(rows)
    except Exception as exc:
        print("REPRODUCED RESULTS VALIDATOR: FAIL")
        print(str(exc))
        return 2

    audit = pd.DataFrame(rows)
    print("REPRODUCED RESULT CHECK")
    print(audit.to_string(index=False))
    if not bool(audit["pass"].all()):
        print("REPRODUCED RESULTS VALIDATOR: FAIL")
        return 2
    print("REPRODUCED RESULTS VALIDATOR: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
